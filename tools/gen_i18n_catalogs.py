def kt_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def emit_map_entries(catalog: dict[str, str], keys: list[str], indent: str = "        ") -> str:
    lines = []
    for key in keys:
        lines.append(f'{indent}StringKey.{key} to "{kt_escape(catalog[key])}",')
    return "\n".join(lines)


def write_en(keys: list[str]) -> Path:
    body = emit_map_entries(EN, keys)
    text = f"""package com.racktrack.i18n

/** English (source of truth) string catalog. */
object EnStrings : StringProvider {{
    private val catalog: Map<StringKey, String> = mapOf(
{body}
    )

    override fun get(key: StringKey): String =
        catalog[key] ?: error("Missing English string for $key")
}}
"""
    path = OUT_DIR / "EnStrings.kt"
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def write_overlay(object_name: str, catalog: dict[str, str], keys: list[str]) -> Path:
    body = emit_map_entries(catalog, keys)
    text = f"""package com.racktrack.i18n

/** Locale overlay catalog. */
object {object_name} : StringProvider by OverlayStringProvider(
    mapOf(
{body}
    ),
)
"""
    path = OUT_DIR / f"{object_name}.kt"
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def validate(name: str, catalog: dict[str, str], keys: list[str]) -> None:
    missing = [k for k in keys if k not in catalog]
    extra = [k for k in catalog if k not in keys]
    if missing or extra:
        raise SystemExit(f"{name}: missing={missing} extra={extra}")
    for k in keys:
        if "{0}" in EN[k] and "{0}" not in catalog[k]:
            raise SystemExit(f"{name}: {k} lost {{0}} placeholder")


def main() -> None:
    keys = list(EN.keys())
    locales = [
        ("EN", EN, None),
        ("FR", FR, "FrStrings"),
        ("DE", DE, "DeStrings"),
        ("ES", ES, "EsStrings"),
        ("IT", IT, "ItStrings"),
        ("NL", NL, "NlStrings"),
        ("PT", PT, "PtStrings"),
    ]
    for name, catalog, _ in locales:
        validate(name, catalog, keys)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    written: list[tuple[str, int]] = []

    write_en(keys)
    written.append(("EnStrings.kt", len(keys)))

    for name, catalog, obj in locales[1:]:
        assert obj is not None
        write_overlay(obj, catalog, keys)
        written.append((f"{obj}.kt", len(catalog)))

    print(f"Wrote {len(written)} catalogs to {OUT_DIR}")
    for fname, count in written:
        print(f"  {fname}: {count} keys")


if __name__ == "__main__":
    main()
